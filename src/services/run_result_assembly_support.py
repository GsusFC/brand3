"""Support helpers for final run result assembly."""

from __future__ import annotations


def emit_summary_output(*, service, discovery_payload: dict, brand_score, summary: str) -> None:
    print("[4/4] Generating report...\n")
    print(summary)
    print("\n".join([""] + service.format_discovery_summary(discovery_payload)))
    service._print_feature_details(brand_score)


